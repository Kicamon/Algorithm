#include <functional>
#include <iostream>
#include <vector>
using namespace std;

class BIT {
    private:
        vector<int> a;
        int n;

    public:
        BIT(int _n) {
                n = _n;
                a.resize(n + 1);
        }

        int lowbit(int x) {
                return x & -x;
        }

        void modify(int x, int d) {
                if (x == 0) {
                        return;
                }
                for (int i = x; i <= n; i += lowbit(i)) {
                        a[i] += d;
                }
        }

        int query(int x) {
                if (x > n) {
                        return 0;
                }
                int res = 0;
                for (int i = x; i; i -= lowbit(i)) {
                        res += a[i];
                }
                return res;
        }
};

int main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int n, m;
        cin >> n >> m;
        BIT bit(n);
        for (int i = 1, t; i <= n; ++i) {
                cin >> t;
                bit.modify(i, t);
        }
        int op, x, y;
        while (m--) {
                cin >> op;
                if (op == 1) {
                        cin >> x >> y;
                        bit.modify(x, y);
                } else {
                        cin >> x;
                        cout << bit.query(x) - bit.query(x - 1) << '\n';
                }
        }

        return 0;
}
