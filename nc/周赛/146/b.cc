#include <iostream>
using namespace std;

int main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int n, k;
        cin >> n >> k;
        long long ans = abs(k);
        for (int i = 0, x, y; i < n; ++i) {
                cin >> x >> y;
                ans = min(ans, 1ll * abs(x) + abs(k - y));
        }
        cout << ans << '\n';

        return 0;
}
