#include <algorithm>
#include <iostream>
#include <vector>
using namespace std;
using ll = long long;

int main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int n, a, b;
        cin >> n >> a >> b;
        vector<ll> num(14);
        for (int i = 0, t; i < n; ++i) {
                cin >> t;
                num[t]++;
        }
        n = *max_element(num.begin(), num.end());
        vector<vector<ll>> dp(14, vector<ll>(n + 1));
        for (int i = 1; i <= 13; ++i) {
                for (int j = 0; j <= num[i]; ++j) {
                        dp[i][j] = (num[i] - j) / 3 * b;
                }
        }
        for (int i = 3; i <= 13; ++i) {
                for (int j = 0; j <= num[i]; ++j) {
                        dp[i][j] = dp[i - 3][j];
                }
        }

        return 0;
}
