#include <iostream>
#include <map>
using namespace std;

void solve() {
        int n;
        cin >> n;
        map<int, int> num;
        for (int i = 0, t; i < n; ++i) {
                cin >> t;
                num[t]++;
        }
        for (auto [_, t] : num) {
                if (t % 2) {
                        cout << "red\n";
                        return;
                }
        }
        cout << "fang\n";
}

int main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int t;
        cin >> t;
        while (t--) {
                solve();
        }

        return 0;
}
