#include <array>
#include <iostream>
using namespace std;
using ll = long long;

int main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int n;
        cin >> n;
        string s;
        cin >> s;
        s = ' ' + s;
        array<int, 2> pre = { 0, 0 };
        ll ans = 0;
        for (int i = 1; i <= n; ++i) {
                int c = s[i] - '0';
                pre[c] = i;
                ans += pre[1 - c];
        }
        cout << ans;

        return 0;
}
