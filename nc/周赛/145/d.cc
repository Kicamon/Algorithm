#include <algorithm>
#include <iostream>
#include <vector>
using namespace std;

int main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int n;
        cin >> n;
        vector<int> a(n), b(n), c(n);
        vector<int> vis(n + 1);
        vector<bool> visb(n + 1), visc(n + 1);
        int idxb = 1, idxc = 1;
        int t = n / 2;
        for (int i = 0; i < n; ++i) {
                cin >> a[i];
                vis[a[i]]++;

                if (t && visb[a[i]] == false) {
                        b[i] = a[i];
                        visb[a[i]] = true;
                        t--;
                } else {
                        c[i] = a[i];
                        visc[a[i]] = true;
                }
        }
        if (t || *max_element(vis.begin(), vis.end()) > 2) {
                cout << -1;
                return 0;
        }

        for (int i = 0; i < n; ++i) {
                if (!b[i]) {
                        while (visb[idxb]) {
                                idxb++;
                        }
                        b[i] = idxb++;
                }
                cout << b[i] << " \n"[i == n - 1];
        }
        for (int i = 0; i < n; ++i) {
                if (!c[i]) {
                        while (visc[idxc]) {
                                idxc++;
                        }
                        c[i] = idxc++;
                }
                cout << c[i] << " \n"[i == n - 1];
        }

        return 0;
}
