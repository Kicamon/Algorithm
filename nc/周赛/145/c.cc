#include <iostream>
#include <numeric>
#include <vector>
using namespace std;

int main() {
#define int long long
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int n;
        cin >> n;
        vector<int> num(n);
        string s;
        for (int &x : num) {
                cin >> x;
        }
        cin >> s;

        int a = 0;
        for (char c : s) {
                a += c == '0';
        }
        int b = n - a;
        int t = lcm(a, b);
        a = t / a, b = t / b;

        for (int i = 0; i < n; ++i) {
                if (s[i] == '0') {
                        num[i] *= a;
                } else {
                        num[i] *= b;
                }
        }

        vector<int> sum(2);
        for (int i = 0; i < n; ++i) {
                sum[s[i] - '0'] += num[i];
        }
        t = abs(sum[0] - sum[1]);
        if (t % (a + b)) {
                cout << -1;
        } else {
                cout << t / (a + b);
        }

        return 0;
}
