#include <algorithm>
#include <iostream>
#include <vector>
using namespace std;

signed main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int n;
        cin >> n;
        vector<int> num(4);
        string s;
        cin >> s;
        for (char c : s) {
                num[c - 'A']++;
        }
        if (max_element(num.begin(), num.end()) == min_element(num.begin(), num.end())) {
                cout << "Yes\n";
        } else {
                cout << "No\n";
        }

        return 0;
}
