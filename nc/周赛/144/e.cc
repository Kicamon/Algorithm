#include <functional>
#include <iostream>
#include <queue>
#include <vector>
#include <array>
using namespace std;
using ll = long long;

struct node {
        int h;
        priority_queue<array<int, 2>, vector<array<int, 2>>, greater<array<int, 2>>> q;
};

int main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int n;
        cin >> n;
        vector<node> a(n + 1);
        vector<int> f(n + 1);
        for (int i = 1; i <= n; ++i) {
                cin >> a[i].h;
        }
        for (int i = 2; i <= n; ++i) {
                cin >> f[i];
        }
        for (int i = 2, t; i <= n; ++i) {
                cin >> t;
                a[f[i]].q.push({ t, i });
        }

        vector<ll> ans(n + 1);
        ll sum = 0;

        function<void(int)> dfs = [&](int u) {
                array<int, 2> t = { 0, 0 };
                auto &q = a[u].q;

                while (!q.empty()) {
                        sum += q.top()[0] - t[0];
                        t = q.top();
                        q.pop();
                        dfs(t[1]);
                }

                sum += a[u].h - t[0];
                ans[u] = sum;
        };

        dfs(1);

        for (int i = 1; i <= n; ++i) {
                cout << ans[i] << ' ';
        }

        return 0;
}
