#include <iostream>
#include <vector>
using namespace std;

signed main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int n;
        cin >> n;
        vector<vector<int>> a(n + 1, vector<int>(n + 1));
        vector<bool> vis(n * n + 1);
        for (int i = n; i; --i) {
                int t = 1;
                for (int j = 1; j <= n; ++j) {
                        while (i * t <= n * n && vis[i * t]) {
                                t++;
                        }
                        if (i * t > n * n) {
                                cout << -1 << '\n';
                                return 0;
                        }
                        vis[i * t] = true;
                        a[i][j] = i * t++;
                }
        }
        for (int j = 1; j <= n; ++j) {
                for (int i = 1; i <= n; ++i) {
                        cout << a[i][j] << ' ';
                }
                cout << '\n';
        }

        return 0;
}
