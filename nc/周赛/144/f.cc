#include <functional>
#include <iostream>
#include <vector>
using namespace std;

struct Node {
        int w;
        vector<int> g;
};

int main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int n;
        cin >> n;
        vector<Node> a(n + 1);
        vector<vector<int>> g(n + 1);
        vector<bool> vis(n + 1);
        for (int i = 1; i <= n; ++i) {
                cin >> a[i].w;
        }
        for (int i = 1, u, v; i < n; ++i) {
                cin >> u >> v;
                a[u].g.push_back(v);
                a[v].g.push_back(u);
        }

        function<void(int, int)> dfs = [&](int u, int f) {
                vis[u] = true;
                if (a[u].g.size() == 1) {
                        return;
                }

                for (int v : a[u].g) {
                        if (v == f) {
                                continue;
                        }
                        dfs(v, u);
                        if (vis[v]) {
                                if (!a[v].w) {
                                        a[f].w ^= 1;
                                        a[u].w ^= 1;
                                        a[v].w ^= 1;
                                }
                        }
                }
        };

        for (int u : a[1].g) {
                dfs(u, 1);
        }

        int ans = 0;
        for (int i = 1; i <= n; ++i) {
                ans += a[i].w;
        }

        if (!a[1].w) {
                for (int v : a[1].g) {
                        if (!a[v].w && a[v].g.size() > 1) {
                                ans++;
                                break;
                        }
                }
        }

        cout << ans;

        return 0;
}
