#include <iostream>
#include <vector>
using namespace std;
const int mod = 998244353;
using ll = long long;

int main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int n, r;
        cin >> n >> r;
        vector<vector<ll>> dp(n + 1, vector<ll>(4));
        dp[0] = { 1, 1, 0, 1 };
        for (int i = 1; i < n; ++i) {
                for (int j = 0; j <= 3; ++j) {
                        (dp[i][j] += dp[i - 1][j]) %= mod;
                        (dp[i][(j + 1) % 4] += dp[i - 1][j]) %= mod;
                        (dp[i][(j + 3) % 4] += dp[i - 1][j]) %= mod;
                }
        }
        cout << dp[n - 1][r];

        return 0;
}
