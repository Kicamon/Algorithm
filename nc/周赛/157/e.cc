#include <iostream>
#include <vector>
using namespace std;
using ll = long long;
const ll suf = 0x3f3f3f3f3f3f3f3fL;

int main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int n, q;
        cin >> n >> q;
        vector<ll> a(n + 1), num(n + 1), min_prev(n + 1, suf), min_next(n + 2, suf);
        string s;
        for (int i = 1; i <= n; ++i) {
                cin >> a[i];
        }
        cin >> s;
        s = " " + s;
        for (int i = 1; i <= n; ++i) {
                num[i] = num[i - 1] + (s[i] == '-' ? -1 : 1) * a[i];
                if (i != 1) {
                        min_prev[i] = min(min_prev[i - 1], num[i - 1]);
                }
        }
        for (int i = n; i; --i) {
                min_next[i] = min(min_next[i + 1], num[i]);
        }

        int p;
        char c;
        while (q--) {
                cin >> p >> c;
                if (min_prev[p] < 0) {
                        cout << "NO\n";
                        continue;
                }
                ll t = ((c == '-' ? -1 : 1) - (s[p] == '-' ? -1 : 1)) * a[p];
                if (min_next[p] + t < 0) {
                        cout << "NO\n";
                        continue;
                }
                cout << "YES\n";
        }

        return 0;
}
