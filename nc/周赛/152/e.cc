#include <iostream>
#include <vector>
#include <array>
#include <algorithm>
using namespace std;
using ll = long long;

int main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int n;
        cin >> n;
        vector<ll> a(n + 1), b(n + 1);
        for (int i = 1; i <= n; ++i) {
                cin >> a[i];
        }
        for (int i = 1; i <= n; ++i) {
                cin >> b[i];
        }
        vector<array<ll, 2>> dp(n + 1);
        for (int i = 1; i <= n; ++i) {
                if (a[i] <= 0) {
                        ll t = max(dp[i - 1][0], dp[i - 1][1]);
                        dp[i] = { t, t };
                        continue;
                }
                ll t = b[i] / 2;
                if (b[i] % 2) {
                        dp[i][0] = t * a[i] + max(dp[i - 1][0], dp[i - 1][1]);
                        dp[i][1] = max((t + 1) * a[i] + dp[i - 1][0], dp[i - 1][1]);
                } else {
                        dp[i][0] = max(t * a[i] + dp[i - 1][0], (t - 1) * a[i] + dp[i - 1][1]);
                        dp[i][1] = t * a[i] + max(dp[i - 1][0], dp[i - 1][1]);
                }
        }
        cout << max(dp[n][0], dp[n][1]);

        return 0;
}
