#include <iostream>
using namespace std;

int main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int n;
        cin >> n;
        if (n > 21) {
                cout << -1;
                return 0;
        }
        for (int i = 0; i < 7; i++) {
                for (int j = 0; j < 6; j++) {
                        if (j % 2 == i % 2) {
                                if (n) {
                                        cout << "1 ";
                                        n--;
                                } else {
                                        cout << "0 ";
                                }
                        } else {
                                cout << "0 ";
                        }
                }
                cout << '\n';
        }

        return 0;
}
