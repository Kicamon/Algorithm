#include <iostream>
#include <vector>
#include <array>
using namespace std;
using ll = long long;

ll f(const array<int, 2> &a, const array<int, 2> &b, const array<int, 2> &c) {
        return 1ll * (a[0] - b[0]) * c[1] - 1ll * (a[1] - b[1]) * c[0] - 1ll * b[1] * a[0]
               + 1ll * a[1] * b[0];
}

int main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int n, ans = 0;
        cin >> n;
        vector<array<int, 2>> a(n);
        for (int i = 0; i < n; ++i) {
                cin >> a[i][0] >> a[i][1];
        }
        for (int i = 0; i < n; ++i) {
                for (int j = i + 1; j < n; ++j) {
                        array<int, 2> cnt = { 0, 0 };
                        for (int k = 0; k < n; ++k) {
                                if (k == i || k == j) {
                                        continue;
                                }
                                if (f(a[i], a[j], a[k]) < 0) {
                                        cnt[0]++;
                                }
                                if (f(a[i], a[j], a[k]) > 0) {
                                        cnt[1]++;
                                }
                        }
                        ans += cnt[0] == cnt[1];
                }
        }
        cout << ans;

        return 0;
}
