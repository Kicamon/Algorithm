#include <iostream>
using namespace std;

int main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int n, m, k, t = 1;
        cin >> n >> m >> k;
        if (n * m - k < k) {
                t = 0;
                k = n * m - k;
        }
        if (k < (n / 2) * (m / 2)) {
                cout << "No\n";
        } else {
                cout << "Yes\n";
                k -= (n / 2) * (m / 2);
                for (int i = 0; i < n; ++i) {
                        for (int j = 0; j < m; ++j) {
                                if (i % 2 && j % 2) {
                                        cout << t;
                                } else if (i % 2 == 0 && j % 2 == 0) {
                                        cout << 1 - t;
                                } else if (k > 0) {
                                        cout << t;
                                        k--;
                                } else {
                                        cout << 1 - t;
                                }
                        }
                        cout << '\n';
                }
        }

        return 0;
}
