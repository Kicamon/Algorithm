#include <iostream>
using namespace std;

void solve() {
        string s;
        cin >> s;
        for (int i = 0; i < (int)s.size(); ++i) {
                if (i == s.size() - 1) {
                        s.erase(s.begin() + i, s.end());
                        break;
                }
                if (s[i] == '0' && s[i + 1] == '1') {
                        s.erase(s.begin() + i, s.begin() + i + 1);
                        break;
                }
        }
        for (int i = 0; i < (int)s.size(); ++i) {
                if (i == s.size() - 1) {
                        s.erase(s.begin() + i, s.end());
                        break;
                }
                if (s[i] == '1' && s[i + 1] == '0') {
                        s.erase(s.begin() + i, s.begin() + i + 1);
                        break;
                }
        }
        cout << s << '\n';
}

int main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int t;
        cin >> t;
        while (t--) {
                solve();
        }

        return 0;
}
