#include <algorithm>
#include <iostream>
#include <set>
#include <vector>
#include <array>
using namespace std;
using ll = long long;

void solve() {
        int n, m;
        cin >> n >> m;
        vector<array<int, 2>> a(n);
        vector<ll> prev(n + 1);
        for (int i = 0; i < n; ++i) {
                cin >> a[i][1] >> a[i][0];
        }
        sort(a.rbegin(), a.rend());
        multiset<int> st;
        ll maxn = 0, cur = 0;
        int idx = 0;
        for (int i = n; ~i; --i) {
                while (idx < n && a[idx][0] >= i) {
                        cur += a[idx][1];
                        st.insert(a[idx][1]);
                        idx++;
                }
                while ((int)st.size() > i + 1) {
                        cur -= *st.begin();
                        st.erase(st.begin());
                }
                maxn = max(maxn, cur);
                if ((int)st.size() <= i) {
                        prev[i] = cur;
                } else {
                        prev[i] = cur - *st.begin();
                }
        }
        for (int i = 1; i <= n; ++i) {
                prev[i] = max(prev[i], prev[i - 1]);
        }
        for (int i = 0, x, y; i < m; ++i) {
                cin >> x >> y;
                cout << max(maxn, prev[y] + x) << " \n"[i == m - 1];
        }
}

signed main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int t;
        cin >> t;
        while (t--) {
                solve();
        }

        return 0;
}
