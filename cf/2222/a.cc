#include <iostream>
#include <vector>
using namespace std;

void solve() {
        int n;
        cin >> n;
        int m = n * 100;
        vector<vector<int>> dp(2, vector<int>(m + 1));
        dp[0][0] = dp[1][0] = true;
        int idx = 0;
        for (int i = 0, x; i < n; ++i) {
                idx ^= 1;
                dp[idx] = dp[idx ^ 1];
                cin >> x;
                for (int j = 1; j <= x; ++j) {
                        int t = j * 100 / x;
                        for (int k = 0; k <= m; ++k) {
                                if (k + t > m) {
                                        break;
                                }
                                dp[idx][k + t] |= dp[idx ^ 1][k];
                        }
                }
        }
        for (int i = 0; i <= m; ++i) {
                if (!dp[idx][i]) {
                        cout << "No\n";
                        return;
                }
        }
        cout << "Yes\n";
}

signed main() {
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int t;
        cin >> t;
        while (t--) {
                solve();
        }

        return 0;
}
